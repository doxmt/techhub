-- TechHub data model on Neon. Keep the original Supabase user IDs so saved
-- content remains attached while the authentication provider is migrated.
CREATE TABLE IF NOT EXISTS legacy_users (
  id uuid PRIMARY KEY,
  email text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS profiles (
  user_id uuid PRIMARY KEY REFERENCES legacy_users(id) ON DELETE CASCADE,
  email text NOT NULL,
  nickname text NOT NULL DEFAULT '' CHECK (char_length(nickname) <= 20),
  role text NOT NULL DEFAULT 'viewer',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  slug text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS content_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url text NOT NULL UNIQUE,
  type text NOT NULL CHECK (type IN ('article', 'youtube')),
  title text NOT NULL,
  description text,
  thumbnail text,
  source text,
  language text CHECK (language IN ('ko', 'en')),
  slug text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  search_vector tsvector GENERATED ALWAYS AS (
    to_tsvector('simple', coalesce(title, '') || ' ' ||
      coalesce(description, '') || ' ' || coalesce(source, ''))
  ) STORED,
  view_count integer NOT NULL DEFAULT 0,
  likes_count integer NOT NULL DEFAULT 0,
  section text NOT NULL DEFAULT 'article'
    CHECK (section IN ('article', 'news', 'contest')),
  deadline timestamptz,
  contest_type text CHECK (
    contest_type IS NULL OR contest_type IN
      ('hackathon', 'dev-contest', 'idea-contest', 'data-competition')
  ),
  CONSTRAINT content_items_published_at_required
    CHECK (status <> 'published' OR published_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS content_categories (
  content_id bigint NOT NULL REFERENCES content_items(id) ON DELETE CASCADE,
  category_id bigint NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  PRIMARY KEY (content_id, category_id)
);

CREATE TABLE IF NOT EXISTS content_tags (
  content_id bigint NOT NULL REFERENCES content_items(id) ON DELETE CASCADE,
  tag_id bigint NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (content_id, tag_id)
);

CREATE TABLE IF NOT EXISTS sources (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  feed_url text NOT NULL UNIQUE,
  feed_type text NOT NULL CHECK (feed_type IN ('rss', 'atom', 'wevity', 'contestkorea')),
  default_language text NOT NULL DEFAULT 'ko' CHECK (default_language IN ('ko', 'en')),
  default_category_id bigint REFERENCES categories(id) ON DELETE SET NULL,
  is_active boolean NOT NULL DEFAULT true,
  last_ingested_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  section text NOT NULL DEFAULT 'article' CHECK (section IN ('article', 'news', 'contest'))
);

CREATE TABLE IF NOT EXISTS ingestion_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id bigint REFERENCES sources(id) ON DELETE SET NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status text NOT NULL CHECK (status IN ('running', 'success', 'partial', 'failed')),
  processed_count integer NOT NULL DEFAULT 0,
  created_count integer NOT NULL DEFAULT 0,
  skipped_count integer NOT NULL DEFAULT 0,
  failed_count integer NOT NULL DEFAULT 0,
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bookmarks (
  user_id uuid NOT NULL REFERENCES legacy_users(id) ON DELETE CASCADE,
  content_id bigint NOT NULL REFERENCES content_items(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, content_id)
);

CREATE TABLE IF NOT EXISTS likes (
  user_id uuid NOT NULL REFERENCES legacy_users(id) ON DELETE CASCADE,
  content_id bigint NOT NULL REFERENCES content_items(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, content_id)
);

CREATE INDEX IF NOT EXISTS idx_content_items_feed ON content_items
  (published_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX IF NOT EXISTS idx_content_items_section_feed ON content_items
  (section, published_at DESC, id DESC) WHERE status = 'published';
CREATE INDEX IF NOT EXISTS idx_content_items_search_vector ON content_items
  USING GIN (search_vector);
CREATE INDEX IF NOT EXISTS idx_content_items_status ON content_items(status);
CREATE INDEX IF NOT EXISTS idx_content_items_contest_deadline ON content_items
  (deadline, id DESC) WHERE section = 'contest';
